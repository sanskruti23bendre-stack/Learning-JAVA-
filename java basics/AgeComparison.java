class AgeComparison {
    public static void main(String[] args) {

        int age1 = 20;
        int age2 = 25;

        System.out.println("Age 1 = " + age1);
        System.out.println("Age 2 = " + age2);

        System.out.println("Age1 > Age2: " + (age1 > age2));
        System.out.println("Age1 < Age2: " + (age1 < age2));
        System.out.println("Age1 == Age2: " + (age1 == age2));
        System.out.println("Age1 != Age2: " + (age1 != age2));
        System.out.println("Age1 >= Age2: " + (age1 >= age2));
        System.out.println("Age1 <= Age2: " + (age1 <= age2));
    }
}