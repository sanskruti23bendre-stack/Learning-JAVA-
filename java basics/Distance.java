class Distance {
    public static void main(String[] args) {

        double km = 5;

        double metres = km * 1000;
        double centimetres = km * 100000;

        System.out.println("Kilometres = " + km);
        System.out.println("Metres = " + metres);
        System.out.println("Centimetres = " + centimetres);
    }
}